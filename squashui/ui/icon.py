def app_icon_pixmap() -> QPixmap:
    """The SquashUI pumpkin: squashui.png / squashui.ico beside the app if present, else the embedded copy."""
    for name in ("squashui.png", "squashui.ico"):
        pix = QPixmap(str(APP_DIR / name))
        if not pix.isNull():
            return pix
    pix = QPixmap()
    pix.loadFromData(base64.b64decode(APP_ICON_PNG_B64), "PNG")
    return pix


def make_app_icon() -> QIcon:
    """Window / taskbar icon, scaled smoothly to each size the shell asks for."""
    source = app_icon_pixmap()
    icon = QIcon()
    for size in (16, 24, 32, 48, 64, 128, 256):
        icon.addPixmap(source.scaled(size, size, Qt.AspectRatioMode.KeepAspectRatio, Qt.TransformationMode.SmoothTransformation))
    return icon
